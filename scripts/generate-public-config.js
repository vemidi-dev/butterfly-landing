'use strict';

const fs = require('fs');
const path = require('path');
const { resolvePublicConfig } = require('../lib/checkout-handoff');

const root = path.join(__dirname, '..');
const outputPath = path.join(root, 'public-config.js');

const config = resolvePublicConfig(process.env);

const contents = `/* Generated by scripts/generate-public-config.js — do not edit manually. */
window.__VEMIDI_PUBLIC_CONFIG__ = Object.freeze(${JSON.stringify(config, null, 2)});
`;

fs.writeFileSync(outputPath, contents, 'utf8');
console.log(`Wrote ${path.relative(root, outputPath)}`);
